export function withSearchKeywords(item: APIReferenceItem): APIReferenceItem {
  const { name = '', overloadId } = item.definition
  const method = name.replace(/^(Game|Sprite)\./, '')
  const keys = [method, name, `${method}#${overloadId}`]
  return {
    ...item,
    searchKeywords: [...new Set([...(item.searchKeywords ?? []), ...keys.flatMap((key) => searchKeywords[key] ?? [])])]
  }
}
